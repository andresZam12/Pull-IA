import { Category } from "@/types";

export interface ArticleItem {
  id: string;
  url: string;
  sourceName: string;
  sourceUrl?: string;
  publishedAt: Date | string | null;
  summary: {
    titleEs: string;
    titleEn: string;
    summaryEs: string;
    summaryEn: string;
    category: Category | string;
    keyPoints: string[];
    relevanceScore: number;
    aiModel: string;
  } | null;
}

interface NewsCardProps {
  article: ArticleItem;
  locale?: "es" | "en";
}

const categoryStyles: Record<Category, { bg: string; text: string; labelEs: string; labelEn: string }> = {
  [Category.AI]: {
    bg: "bg-purple-500/10 border-purple-500/30 text-purple-300",
    text: "text-purple-400",
    labelEs: "Inteligencia Artificial",
    labelEn: "AI",
  },
  [Category.ENGINEERING]: {
    bg: "bg-blue-500/10 border-blue-500/30 text-blue-300",
    text: "text-blue-400",
    labelEs: "Ingeniería",
    labelEn: "Engineering",
  },
  [Category.PROGRAMMING]: {
    bg: "bg-emerald-500/10 border-emerald-500/30 text-emerald-300",
    text: "text-emerald-400",
    labelEs: "Programación",
    labelEn: "Programming",
  },
  [Category.EMPLOYABILITY]: {
    bg: "bg-amber-500/10 border-amber-500/30 text-amber-300",
    text: "text-amber-400",
    labelEs: "Empleabilidad",
    labelEn: "Careers",
  },
};

export function NewsCard({ article, locale = "es" }: NewsCardProps) {
  const summary = article.summary;
  if (!summary) return null;

  const category = (summary.category as Category) || Category.ENGINEERING;
  const catStyle = categoryStyles[category] || categoryStyles[Category.ENGINEERING];
  
  const title = locale === "es" ? summary.titleEs : summary.titleEn;
  const description = locale === "es" ? summary.summaryEs : summary.summaryEn;
  const categoryLabel = locale === "es" ? catStyle.labelEs : catStyle.labelEn;

  // Format date
  const dateStr = article.publishedAt
    ? new Date(article.publishedAt).toLocaleDateString(locale === "es" ? "es-CO" : "en-US", {
        month: "short",
        day: "numeric",
        year: "numeric",
      })
    : null;

  return (
    <article className="group relative flex flex-col justify-between overflow-hidden rounded-2xl border border-zinc-800/90 bg-zinc-900/60 p-6 backdrop-blur-sm transition-all duration-300 hover:-translate-y-1 hover:border-zinc-700 hover:bg-zinc-900/90 hover:shadow-xl hover:shadow-indigo-500/5">
      <div>
        {/* Header: Category Badge + Source + Date */}
        <div className="mb-4 flex flex-wrap items-center justify-between gap-2 text-xs">
          <span className={`inline-flex items-center rounded-full border px-2.5 py-0.5 font-medium ${catStyle.bg}`}>
            {categoryLabel}
          </span>
          
          <div className="flex items-center gap-2 text-zinc-400">
            <span className="font-semibold text-zinc-300">{article.sourceName}</span>
            {dateStr && (
              <>
                <span>•</span>
                <time dateTime={new Date(article.publishedAt!).toISOString()}>{dateStr}</time>
              </>
            )}
          </div>
        </div>

        {/* Title */}
        <h3 className="mb-3 text-lg font-bold tracking-tight text-white transition group-hover:text-indigo-300 sm:text-xl">
          <a href={article.url} target="_blank" rel="noopener noreferrer" className="focus:outline-none">
            <span className="absolute inset-0" aria-hidden="true" />
            {title}
          </a>
        </h3>

        {/* Summary */}
        <p className="mb-4 line-clamp-3 text-sm leading-relaxed text-zinc-300">
          {description}
        </p>

        {/* Key Points (bullets generated by Gemini) */}
        {summary.keyPoints && summary.keyPoints.length > 0 && (
          <ul className="mb-5 space-y-1.5 border-t border-zinc-800/70 pt-3 text-xs text-zinc-400">
            {summary.keyPoints.slice(0, 3).map((point, index) => (
              <li key={index} className="flex items-start gap-1.5">
                <span className="mt-1 h-1 w-1 shrink-0 rounded-full bg-indigo-400" />
                <span className="line-clamp-2">{point}</span>
              </li>
            ))}
          </ul>
        )}
      </div>

      {/* Footer: AI verification & Original source link */}
      <div className="relative z-10 flex items-center justify-between border-t border-zinc-800/60 pt-4 text-xs">
        <div className="flex items-center gap-1.5 text-zinc-300">
          <svg className="h-3.5 w-3.5 text-emerald-400" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M5 13l4 4L19 7" />
          </svg>
          <span>{locale === "es" ? "Resumen verificado con IA" : "AI verified summary"}</span>
        </div>

        <span className="inline-flex items-center gap-1 font-medium text-indigo-400 transition group-hover:text-indigo-300">
          {locale === "es" ? "Fuente original" : "Original source"}
          <svg className="h-3.5 w-3.5 transition-transform group-hover:translate-x-0.5" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M10 6H6a2 2 0 00-2 2v10a2 2 0 002 2h10a2 2 0 002-2v-4M14 4h6m0 0v6m0-6L10 14" />
          </svg>
        </span>
      </div>
    </article>
  );
}
